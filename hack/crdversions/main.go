// Command crdversions adds the versions from before v1 to a generated
// definition of Application or Bookmark.
//
// The older versions only ever added fields, and v1 has the fields of the
// last of them. So every version is served with the schema of v1, v1 is the
// one objects are stored in, and no conversion is needed: an object written
// through any version reads the same through every other.
//
// Usage: crdversions <generated definition> <output>
package main

import (
	"fmt"
	"os"

	"sigs.k8s.io/yaml"

	apiv1 "github.com/ullbergm/startpunkt/api/v1"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: crdversions <generated definition> <output>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "crdversions:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	data, err := os.ReadFile(in)
	if err != nil {
		return err
	}
	result, err := addVersions(data)
	if err != nil {
		return fmt.Errorf("%s: %w", in, err)
	}
	return os.WriteFile(out, result, 0o644)
}

// addVersions returns the definition with one version per deprecated
// version after the generated one, each a copy of it that is served,
// deprecated and not stored.
func addVersions(definition []byte) ([]byte, error) {
	var crd map[string]any
	if err := yaml.Unmarshal(definition, &crd); err != nil {
		return nil, err
	}
	spec, _ := crd["spec"].(map[string]any)
	versions, _ := spec["versions"].([]any)
	names, _ := spec["names"].(map[string]any)
	if len(versions) != 1 {
		return nil, fmt.Errorf("expected one generated version, found %d", len(versions))
	}
	current, _ := versions[0].(map[string]any)
	if current["name"] != apiv1.Version {
		return nil, fmt.Errorf("expected version %s, found %v", apiv1.Version, current["name"])
	}
	current["storage"] = true
	// Newest first, as kubectl lists them.
	for i := len(apiv1.DeprecatedVersions) - 1; i >= 0; i-- {
		name := apiv1.DeprecatedVersions[i]
		older := map[string]any{}
		for key, value := range current {
			// The values are shared between the versions. They are only
			// read from here on.
			older[key] = value
		}
		older["name"] = name
		older["storage"] = false
		older["deprecated"] = true
		older["deprecationWarning"] = fmt.Sprintf("%s/%s %v is deprecated; use %s/%s",
			apiv1.Group, name, names["kind"], apiv1.Group, apiv1.Version)
		versions = append(versions, older)
	}
	spec["versions"] = versions
	// Explicit, so that nobody has to wonder: the versions differ in name
	// only.
	spec["conversion"] = map[string]any{"strategy": "None"}
	// controller-gen writes an empty status, which is not part of a
	// definition that is applied.
	delete(crd, "status")
	body, err := yaml.Marshal(crd)
	if err != nil {
		return nil, err
	}
	header := "# Generated by `make crds` from the types in api/v1. Do not edit.\n---\n"
	return append([]byte(header), body...), nil
}
